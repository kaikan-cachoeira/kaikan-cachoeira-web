const CUSTO_SEM_VALOR = 0;

function hojeAs(hora, minuto) {
  const date = new Date();
  date.setHours(hora, minuto, 0, 0);
  return date.toISOString();
}

function iso(y, m, d, h = 10, min = 0) {
  return new Date(y, m - 1, d, h, min, 0, 0).toISOString();
}

function lote(id, entryQty, balance, totalCost, createdAt) {
  const unitCost = entryQty > 0 ? totalCost / entryQty : 0;
  return {
    id,
    entryQty,
    balance,
    totalCost: totalCost || 0,
    unitCost: unitCost || 0,
    createdAt,
  };
}

